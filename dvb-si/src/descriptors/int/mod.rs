//! INT descriptor namespace — [`AnyIntDescriptor`] + [`parse_int_loop`].
//!
//! The IP/MAC Notification Table (ETSI EN 301 192 V1.7.1 §8.4) has its OWN
//! descriptor tag space for `0x00..=0x3F` (Table 19, clause 8.4.5.1): "MPEG
//! descriptors in the range 0x00 to 0x3F cannot be used in the INT", and those
//! tags "share a common descriptor name space with UNT descriptors". So
//! INT tag 0x06 is `target_smartcard_descriptor`, never SI/MPEG
//! `data_stream_alignment_descriptor` (issue #1285). Tags `0x40..=0xFF` "shall
//! have their standard semantics as defined in ETSI EN 300 468" (telephone
//! 0x57, private_data_specifier 0x5F, user private) and are dispatched through
//! [`AnyIntDescriptor::Si`].
//!
//! The list below is generated by `declare_scoped_namespace!` (one line per
//! tag, ascending); the loop wrapper [`IntDescriptorLoop`] is what the
//! `platform_descriptor_loop` / `target_descriptor_loop` /
//! `operational_descriptor_loop` of [`IntSection`](crate::tables::int::IntSection)
//! hold.
//!
//! ```
//! use dvb_si::descriptors::int::{parse_int_loop, AnyIntDescriptor};
//!
//! // target_serial_number (INT tag 0x08) then telephone-range SI tag 0x5F
//! // (private_data_specifier) then unknown INT tag 0x20.
//! let raw = [
//!     0x08, 0x02, 0xAB, 0xCD,
//!     0x5F, 0x04, 0x00, 0x00, 0x00, 0x28,
//!     0x20, 0x01, 0xFF,
//! ];
//! let items: Vec<_> = parse_int_loop(&raw).collect();
//! assert!(matches!(items[0].as_ref().unwrap(), AnyIntDescriptor::TargetSerialNumber(_)));
//! assert!(matches!(items[1].as_ref().unwrap(), AnyIntDescriptor::Si(_)));
//! assert!(matches!(items[2].as_ref().unwrap(), AnyIntDescriptor::Unknown { tag: 0x20, .. }));
//! ```

