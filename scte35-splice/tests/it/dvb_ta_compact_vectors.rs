fn parse(bytes: &[u8]) -> CompactScte35 {
    CompactScte35::parse(bytes).expect("independent-oracle vector must parse")
}

fn assert_round_trip(bytes: &[u8]) {
    let v = parse(bytes);
    assert_eq!(
        v.try_to_bytes().unwrap(),
        bytes,
        "serialize must reproduce the independently packed bytes"
    );
}

fn time_signal(bytes: &[u8]) -> CompactTimeSignal {
    match parse(bytes) {
        CompactScte35::TimeSignal(t) => t,
        other => panic!("expected TimeSignal, got {other:?}"),
    }
}

fn splice_insert(bytes: &[u8]) -> CompactSpliceInsert {
    match parse(bytes) {
        CompactScte35::SpliceInsert(s) => s,
        other => panic!("expected SpliceInsert, got {other:?}"),
    }
}

#[test]
fn time_signal_plain() {
    let t = time_signal(&TS_PLAIN);
    assert!(!t.encrypted_packet);
    assert_eq!(t.encryption_algorithm, 0);
    assert_eq!(t.cw_index, 0);
    assert_eq!(t.pts_time, 0x1_2345_6789);
    assert_eq!(t.segmentation_event_id, 0xDEAD_BEEF);
    assert_eq!(t.segmentation_duration, 0xAB_CDEF_0123);
    assert_eq!(t.segmentation_type_id, 0x30);
    assert_eq!(t.segmentation_upid, UPID);
    assert_eq!((t.segments_num, t.segments_expected), (1, 2));
    assert_eq!(t.e_crc_32, None);
    assert_round_trip(&TS_PLAIN);
}

#[test]
fn time_signal_encrypted_with_empty_upid() {
    let t = time_signal(&TS_ENCRYPTED);
    assert!(t.encrypted_packet);
    assert_eq!(t.encryption_algorithm, 5);
    assert_eq!(t.cw_index, 0x7E);
    assert_eq!(t.pts_time, 0x1_FFFF_FFFF);
    assert_eq!(t.segmentation_event_id, 1);
    assert_eq!(t.segmentation_duration, 0x01_0000_0000);
    assert_eq!(t.segmentation_type_id, 0x34);
    assert!(t.segmentation_upid.is_empty());
    assert_eq!((t.segments_num, t.segments_expected), (0xFF, 0));
    assert_eq!(t.e_crc_32, Some(0xCAFE_BABE));
    assert_round_trip(&TS_ENCRYPTED);
}

#[test]
fn splice_insert_plain_without_das() {
    let s = splice_insert(&SI_PLAIN);
    assert!(!s.encrypted_packet);
    assert_eq!(s.pts_time, 0x1234);
    assert_eq!(s.splice_event_id, 0x1122_3344);
    assert_eq!(s.duration, 0x1_0000_0001);
    assert_eq!(s.unique_program_id, 0xBEEF);
    assert_eq!((s.avail_num, s.avails_expected), (7, 9));
    assert_eq!(s.reserved, 0x3F);
    assert!(s.das.is_none());
    assert_eq!(s.e_crc_32, None);
    assert_round_trip(&SI_PLAIN);
}

#[test]
fn splice_insert_reserved_row_is_preserved_not_normalised() {
    let s = splice_insert(&SI_RESERVED_NONDEFAULT);
    assert_eq!(
        s.reserved, 0x2A,
        "a non-default reserved row must survive parse"
    );
    assert_eq!(s.pts_time, 0x1_0000_0000);
    assert_round_trip(&SI_RESERVED_NONDEFAULT);
}

#[test]
fn splice_insert_with_das_body() {
    let s = splice_insert(&SI_WITH_DAS);
    assert_eq!(s.pts_time, 0x1_2345_6789);
    assert_eq!(s.splice_event_id, 0xDEAD_BEEF);
    let das: &CompactDas = s.das.as_ref().expect("DAS_descriptor_flag was set");
    assert_eq!((das.break_num, das.breaks_expected), (1, 3));
    assert_eq!(
        das.equivalent_segmentation_type,
        EquivalentSegmentationType::from_bits(2)
    );
    assert_eq!(das.reserved, 0xF);
    assert_eq!(das.upid, UPID);
    assert_round_trip(&SI_WITH_DAS);
}

#[test]
fn splice_insert_das_with_non_default_reserved_nibble() {
    let s = splice_insert(&SI_DAS_RESERVED_NONDEFAULT);
    let das = s.das.as_ref().unwrap();
    assert_eq!((das.break_num, das.breaks_expected), (2, 4));
    assert_eq!(
        das.equivalent_segmentation_type,
        EquivalentSegmentationType::from_bits(1)
    );
    assert_eq!(das.reserved, 0x5, "DAS reserved nibble preserved");
    assert_eq!(das.upid, b"Q");
    assert_round_trip(&SI_DAS_RESERVED_NONDEFAULT);
}

#[test]
fn splice_insert_encrypted_with_empty_das_and_extreme_values() {
    let s = splice_insert(&SI_ENCRYPTED_DAS);
    assert!(s.encrypted_packet);
    assert_eq!(s.encryption_algorithm, 63);
    assert_eq!(s.cw_index, 0xFF);
    assert_eq!(s.pts_time, 0x1_FFFF_FFFF);
    assert_eq!(s.splice_event_id, 0xFFFF_FFFF);
    assert_eq!(s.duration, 0x1_FFFF_FFFF);
    assert_eq!(s.unique_program_id, 0xFFFF);
    assert_eq!((s.avail_num, s.avails_expected), (255, 255));
    let das = s.das.as_ref().unwrap();
    assert_eq!((das.break_num, das.breaks_expected), (0, 0));
    assert!(das.upid.is_empty());
    assert_eq!(s.e_crc_32, Some(0x0102_0304));
    assert_round_trip(&SI_ENCRYPTED_DAS);
}

/// The vectors must be sensitive to the field widths: flipping one bit of each
/// multi-bit field changes exactly that field (a width/offset bug that shifts
/// a boundary would move the change into a neighbour).
#[test]
fn single_bit_flips_land_in_the_intended_field() {
    // pts_time is bits 15..48 of the body (after message_type); flip its LSB
    // (bit 47 counted from the start of the body = byte 5 bit 0 of the vector).
    let mut v = TS_PLAIN.to_vec();
    v[6] ^= 0x01; // body bit 47: the LSB of pts_time (1+6+8+33 = 48 bits)
    assert_eq!(time_signal(&v).pts_time, 0x1_2345_6789 ^ 1);
    assert_eq!(time_signal(&v).segmentation_event_id, 0xDEAD_BEEF);
    // segmentation_event_id's MSB is body bit 48.
    let mut v = TS_PLAIN.to_vec();
    v[7] ^= 0x80;
    assert_eq!(
        time_signal(&v).segmentation_event_id,
        0xDEAD_BEEF ^ 0x8000_0000
    );
    assert_eq!(time_signal(&v).pts_time, 0x1_2345_6789);
}
