//! Independent-oracle vectors for the DVB TA compact SCTE 35 encoding
//! (ETSI TS 103 752-1 V1.2.1 section 8.3.3, Tables 5, 6 and 8).
//!
//! # Provenance and what this does (not) prove
//!
//! Every byte vector below is produced by
//! `tests/fixtures/dvb_ta/gen_compact_vectors.py`, a plain MSB-first bit packer
//! written ONLY from the "No. of Bits" columns of the V1.2.1 page images
//! (pp.27-28) - it shares no code with this crate, so a field-order or width
//! mistake applied identically in `compact.rs`'s parser and serializer (which
//! the self round-trip tests in `dvb_ta.rs` cannot see) fails here.
//!
//! **No real compact-watermark capture exists** (none in `.test-streams/`, the
//! committed fixtures, or any public corpus we know of), so this is the
//! strongest evidence available: spec table -> independent encoder -> crate
//! decode/encode. It does NOT settle the one place the spec contradicts
//! itself, the nibble order of the DAS body (see "Open question" below).
//!
//! # Open question: nibble order of the DAS body
//!
//! Table 8 (page 28) lists, inside `if (DAS_descriptor_flag)`:
//! `... breaks_expected(8) | equivalent_segmentation_type(4, uimsbf) |
//! reserved(4, bslbf) | upid()`, i.e. the type in the HIGH nibble. The
//! stand-alone `DVB_DAS_descriptor()` Table 1 (V1.1.1 and V1.2.1, page 17)
//! lists the same two rows in the OPPOSITE name order (`reserved` then
//! `equivalent_segmentation_type`) while its mnemonic column (uimsbf, bslbf)
//! matches Table 8's. The crate follows each table's own name order
//! (`das_descriptor.rs`: reserved high / type low; `compact.rs`: type high /
//! reserved low). Without a real DAS-carrying capture this cannot be decided;
//! the tests below pin the crate to Table 8 for the compact form only. Both
//! readings are selectable through `DasNibbleOrder` and pinned in
//! `tests/it/das_nibble_order.rs`; the evidence search is recorded in
//! `docs/dvb_ta/compact-scte35.md`.

