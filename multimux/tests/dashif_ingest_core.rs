use std::path::PathBuf;

use broadcast_common::{Package, Unpackage};
use multimux::dashif_ingest::classify;
use multimux::dashif_ingest::{
    Addressing, IngestError, IngestMethod, IngestState, ManifestFormat, ManifestGrouping,
    ObjectKind, RequestMeta, SegmentDisposition,
};
use transmux::dash::DashPackager;
use transmux::dash_parse::SegmentTemplate;
use transmux::ts_demux::TsDemux;

fn demux_media() -> transmux::media::Media {
    let ts =
        std::fs::read(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../fixtures/ts/h264_aac.ts"))
            .expect("fixture");
    let mut demux = TsDemux::new();
    demux.unpackage(&ts[..]).expect("demux")
}

fn build_mpd() -> String {
    let media = demux_media();
    let mut pkg = DashPackager::default();
    pkg.package(&media).expect("package")
}

// (a) valid MPD generated by transmux's own writer is accepted.
#[test]
fn generated_mpd_accepted() {
    let mpd = build_mpd();
    let g = ManifestGrouping::from_mpd(mpd.as_bytes()).expect("accept");
    assert_eq!(g.init_template, "init-stream$RepresentationID$.m4s");
    assert_eq!(
        g.media_template,
        "chunk-stream$RepresentationID$-$Number$.m4s"
    );
    assert_eq!(g.addressing, Addressing::Number);
    assert_eq!(
        g.switching_sets,
        vec![vec!["1".to_string()], vec!["2".to_string()]]
    );
}

// (b) real committed MPDs: livesim2 (Time addressing) accepted; manifest-inheritance has BaseURL -> rejected.
#[test]
fn committed_mpds() {
    // accepted (Time addressing)
    let p = test_fixtures::path("dash/livesim2/segtimeline_time_a.mpd");
    let bytes = std::fs::read(&p).unwrap();
    let g = ManifestGrouping::from_mpd(&bytes).expect("livesim2 accepted");
    assert_eq!(g.addressing, Addressing::Time);
    assert!(g.media_template.contains("$Time$"));

    // accepted (Number addressing)
    let p = test_fixtures::path("dash/manifest.mpd");
    let bytes = std::fs::read(&p).unwrap();
    let g = ManifestGrouping::from_mpd(&bytes).expect("manifest accepted");
    assert_eq!(g.addressing, Addressing::Number);

    // rejected: BaseURL present
    let p = test_fixtures::path("dash/manifest-inheritance.mpd");
    let bytes = std::fs::read(&p).unwrap();
    let err = ManifestGrouping::from_mpd(&bytes).expect_err("baseurl rejected");
    assert!(matches!(err, IngestError::MpdBaseUrlPresent));

    // accepted: scte35-ssai manifest template
    let p = test_fixtures::path("scte35-ssai/dash/manifest-template.mpd");
    let bytes = std::fs::read(&p).unwrap();
    let _g = ManifestGrouping::from_mpd(&bytes).expect("template accepted");
}

// (c) minimal violating MPDs, one per sub-clause.
#[test]
fn violating_multiple_periods() {
    let mpd = build_mpd();
    let period_start = mpd.find("<Period").unwrap();
    let period_end = mpd.find("</Period>").unwrap() + "</Period>".len();
    let period = &mpd[period_start..period_end];
    let broken = mpd.replacen("</Period>", &format!("</Period>{}", period), 1);
    let err = ManifestGrouping::from_mpd(broken.as_bytes()).unwrap_err();
    assert!(matches!(err, IngestError::MpdMultiplePeriods));
}

#[test]
fn violating_missing_template() {
    let mpd = build_mpd();
    let broken = mpd.replace("<SegmentTemplate ", "<!--x ");
    // remove closing of segment templates by deleting the tag entirely is hard;
    // instead strip the SegmentTemplate element tokens
    let broken = broken.replace("SegmentTemplate ", "Removed ");
    let err = ManifestGrouping::from_mpd(broken.as_bytes()).unwrap_err();
    // any 400-class rejection is acceptable; expect missing-template or mismatch
    assert!(err.status().as_u16() == 400);
}

