#[test]
fn classify_header_and_segment_number() {
    let mpd = build_mpd();
    let g = ManifestGrouping::from_mpd(mpd.as_bytes()).unwrap();
    let rep = &g.switching_sets[0][0];
    let init_path = SegmentTemplate::resolve(&g.init_template, rep, None, None, None);
    let media_path = SegmentTemplate::resolve(&g.media_template, rep, Some(1), None, None);
    let req = RequestMeta {
        method: IngestMethod::Post,
        path: &init_path,
        content_length: Some(10),
        chunked: false,
        body_empty: false,
    };
    let k = classify(&req, Some(&g)).unwrap();
    match k {
        ObjectKind::Header { representation_id } => assert_eq!(representation_id, "1"),
        _ => panic!("expected header"),
    }
    let req = RequestMeta {
        method: IngestMethod::Post,
        path: &media_path,
        content_length: Some(10),
        chunked: false,
        body_empty: false,
    };
    let k = classify(&req, Some(&g)).unwrap();
    match k {
        ObjectKind::Segment {
            representation_id,
            number,
            time,
        } => {
            assert_eq!(representation_id, "1");
            assert_eq!(number, Some(1));
            assert_eq!(time, None);
        }
        _ => panic!("expected segment"),
    }
}

